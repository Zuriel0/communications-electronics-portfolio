// Local generated-byte comparison. Compression is gzip level 9, not a network metric.
import {readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {createHash} from 'node:crypto';
import {gzipSync} from 'node:zlib';

const baseline = process.argv[2];
if (!baseline) throw new Error('Usage: node scripts/measure-case-bundles.mjs BASELINE_DIST [OUTPUT_JSON]');
async function inventory(directory) {
  const root=resolve(directory);
  const manifest=JSON.parse(await readFile(resolve(root,'.vite/manifest.json'),'utf8'));
  const files=[];
  for (const [key,item] of Object.entries(manifest)) {
    if (!/\.(js|css)$/.test(item.file)) continue;
    const data=await readFile(resolve(root,item.file));
    files.push({key,file:item.file,bytes:data.length,gzip9:gzipSync(data,{level:9}).length,
      sha256:createHash('sha256').update(data).digest('hex'),imports:item.imports || [],dynamicImports:item.dynamicImports || [],css:item.css || []});
  }
  // Entry CSS is referenced by the JS entry but need not have its own manifest row.
  for (const file of new Set(Object.values(manifest).flatMap(item=>item.css || []))) {
    if (files.some(item=>item.file===file)) continue;
    const data=await readFile(resolve(root,file));
    files.push({key:file,file,bytes:data.length,gzip9:gzipSync(data,{level:9}).length,
      sha256:createHash('sha256').update(data).digest('hex'),imports:[],dynamicImports:[],css:[]});
  }
  function closure(key) {
    const visited=new Set();
    function visit(k) { if (visited.has(k)) return; visited.add(k); (manifest[k].imports || []).forEach(visit); }
    visit(key);
    const js=files.filter(x=>visited.has(x.key) && x.file.endsWith('.js'));
    const cssFiles=new Set(js.flatMap(x=>x.css));
    const css=files.filter(x=>cssFiles.has(x.file));
    const sum=(items,field)=>items.reduce((total,x)=>total+x[field],0);
    return {js:sum(js,'bytes'),gzip9:sum(js,'gzip9'),css:sum(css,'bytes'),cssGzip9:sum(css,'gzip9'),
      files:js.map(x=>x.file).sort(),cssFiles:[...cssFiles].sort()};
  }
  return {files,editorialClosures:Object.fromEntries(['index.html','src/pages/projects/Concurrencia.jsx','src/pages/projects/Metodologia.jsx'].map(key=>[key,closure(key)]))};
}
const report={method:'Generated bytes and local Node gzip level 9. Static import closures include the application entry; dynamic diagrams may prefetch near viewport after editorial commit. Not Web Vitals or transferred bytes.',
  baseline:{reference:'ANX-012.1 / 68e9d40',...await inventory(baseline)},candidate:{reference:'ANX-012.2; exact asset hashes listed',...await inventory('dist')}};
await writeFile(resolve(process.argv[3] || 'docs/redesign/reports/anx-012-2/bundles.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(Object.fromEntries(['baseline','candidate'].map(key=>[key,report[key].editorialClosures])),null,2));

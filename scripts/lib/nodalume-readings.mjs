// Semantic projection only: no positions, runtime state, handles or inspection internals.
export function createNodalumeReadings(original, engineering, messages) {
  return [...Object.entries(original).map(([kind,model])=>({...model,kind})),...engineering].map(model=>{
    const view={kind:model.kind,id:model.id,inspected:Boolean(model.inspected),height:model.height||560,mobileHeight:model.mobileHeight||730};
    for(const language of ['en','es']){
      const t=key=>{
        if(!Object.hasOwn(messages[language],key))throw new Error(`Missing ${language} diagram copy: ${key}`);
        return messages[language][key];
      };
      view[language]={title:t(model.title),status:t(model.status),summary:model.summary?t(model.summary):'',relationships:model.edges.map(edge=>`${t(model.nodes.find(node=>node.id===edge.source).label)} — ${t(edge.label)} — ${t(model.nodes.find(node=>node.id===edge.target).label)}`)};
    }
    return view;
  });
}
export function serializeNodalumeReadings(views) {
  return '// Generated by scripts/generate-nodalume-readings.mjs. Do not edit manually.\n// EN/ES semantic HTML remains available independently of the deferred canvas.\nexport const nodalumeReadings = '+JSON.stringify(views,null,2)+';\n';
}
